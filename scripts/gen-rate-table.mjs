// Regenerates src/heavy/rate-table.ts. Committed alongside its output so the
// data file can be diffed rather than trusted: `node scripts/gen-rate-table.mjs`
// then `git diff --exit-code src/heavy/rate-table.ts`.
//
// The table exists only to give the deferred component enough weight that the
// initial-bundle difference is visible in the CLI's own output rather than
// buried in rounding.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const REGIONS = [
  'Abu Dhabi', 'Ajman', 'Al Ain', 'Dubai', 'Fujairah', 'Ras Al Khaimah',
  'Sharjah', 'Umm Al Quwain', 'Riyadh', 'Jeddah', 'Mecca', 'Medina',
  'Dammam', 'Khobar', 'Tabuk', 'Abha', 'Doha', 'Al Rayyan', 'Al Wakrah',
  'Umm Salal', 'Manama', 'Riffa', 'Muharraq', 'Isa Town', 'Kuwait City',
  'Hawalli', 'Salmiya', 'Jahra', 'Muscat', 'Salalah', 'Sohar', 'Nizwa',
  'Amman', 'Irbid', 'Zarqa', 'Aqaba', 'Cairo', 'Alexandria', 'Giza',
  'Port Said',
];

const BANDS = [
  'Standard supply', 'Reduced supply', 'Zero rated export',
  'Exempt financial', 'Reverse charge import', 'Designated zone transfer',
  'Digital service B2C', 'Digital service B2B', 'Transport exempt',
  'Healthcare exempt', 'Education reduced', 'Residential lease',
];

const RATES = [0.05, 0.15, 0, 0, 0.05, 0, 0.05, 0, 0, 0, 0.05, 0];

const rows = [];
let serial = 1000;
for (const region of REGIONS) {
  for (let i = 0; i < BANDS.length; i++) {
    serial++;
    rows.push(
      `  { code: 'RB-${serial}', region: '${region}', band: '${BANDS[i]}', ` +
        `rate: ${RATES[i]}, effective: '2026-01-01', note: '${BANDS[i]} in ${region}, band ${i + 1}' },`,
    );
  }
}

const file = `// GENERATED by scripts/gen-rate-table.mjs — do not hand-edit.
// ${rows.length} rows of filler with a realistic shape, so the deferred
// component is big enough for the bundle difference to be legible.

export interface RateBand {
  readonly code: string;
  readonly region: string;
  readonly band: string;
  readonly rate: number;
  readonly effective: string;
  readonly note: string;
}

export const RATE_BANDS: readonly RateBand[] = [
${rows.join('\n')}
];
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'heavy', 'rate-table.ts');
writeFileSync(out, file, 'utf8');
console.log(`wrote ${rows.length} rows to ${out}`);
